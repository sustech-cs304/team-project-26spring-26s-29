function normalizeLocale(value) {
  const normalized = String(value ?? "").trim().toLowerCase();
  return normalized === "en" || normalized === "english" ? "en" : "zh-CN";
}

function formatTranslation(template, params = {}) {
  return String(template).replace(/\{([A-Za-z0-9_]+)\}/g, (match, key) => {
    if (Object.prototype.hasOwnProperty.call(params, key)) {
      return String(params[key]);
    }
    return match;
  });
}

function createI18n(initialLocale = "zh-CN") {
  const state = {
    locale: normalizeLocale(initialLocale),
  };

  return {
    get locale() {
      return state.locale;
    },
    setLocale(nextLocale) {
      state.locale = normalizeLocale(nextLocale);
      return state.locale;
    },
    t(key, params = {}) {
      const dictionary = TRANSLATIONS[state.locale] || TRANSLATIONS["zh-CN"];
      const fallback = TRANSLATIONS.en[key] || key;
      return formatTranslation(dictionary[key] || fallback, params);
    },
  };
}

function applyDocumentTranslations(i18n, root = document) {
  if (!i18n || !root) {
    return;
  }

  if (root === document) {
    document.documentElement.lang = i18n.locale;
    document.title = i18n.t("app.title");
  }

  root.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = i18n.t(node.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    node.setAttribute("placeholder", i18n.t(node.dataset.i18nPlaceholder));
  });
  root.querySelectorAll("[data-i18n-aria-label]").forEach((node) => {
    node.setAttribute("aria-label", i18n.t(node.dataset.i18nAriaLabel));
  });
}

